create extension if not exists pgcrypto;

-- ---------- Users (owner / staff) ----------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  email       text,
  name        text,
  phone       text,
  role        text not null default 'staff' check (role in ('owner','staff')),
  active      boolean not null default false,
  created_at  timestamptz not null default now()
);

-- ---------- Pump settings (single row) ----------
create table if not exists public.settings (
  id          int primary key default 1 check (id = 1),
  pump_name   text default 'My Petrol Pump',
  company     text,
  address     text,
  gstin       text,
  phone       text,
  lube_gst    numeric(5,2) default 18,
  bill_footer text default 'Thank you for your business.',
  created_at  timestamptz not null default now()
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

-- ---------- Daily fuel rates ----------
create table if not exists public.rates (
  id          uuid primary key default gen_random_uuid(),
  date        date not null,
  petrol      numeric(10,2),
  diesel      numeric(10,2),
  created_by  uuid default auth.uid(),
  created_at  timestamptz not null default now()
);

-- ---------- Lubricants / other items ----------
create table if not exists public.products (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  unit        text default 'pc',
  price       numeric(10,2) not null default 0,     -- price incl. GST
  gst_rate    numeric(5,2) default 18,
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ---------- Credit customers ----------
create table if not exists public.customers (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  type          text default 'individual' check (type in ('fleet','farmer','business','individual')),
  phone         text,
  gstin         text,
  address       text,
  credit_limit  numeric(12,2) default 0,             -- 0 = no limit
  cycle         text default 'monthly' check (cycle in ('weekly','fortnightly','monthly','seasonal','custom')),
  cycle_days    int default 30,
  due_days      int default 7,
  interest_rate numeric(5,2) default 0,              -- % per month on overdue
  msg_lang      text default 'hi' check (msg_lang in ('en','hi','pa')),
  note          text,
  active        boolean not null default true,
  created_at    timestamptz not null default now()
);

-- ---------- Vehicles ----------
create table if not exists public.vehicles (
  id          uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  number      text not null,
  vtype       text,
  fuel        text default 'diesel',
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ---------- Bills / statements ----------
create table if not exists public.bills (
  id          uuid primary key default gen_random_uuid(),
  bill_no     bigint generated by default as identity unique,
  customer_id uuid not null references public.customers(id),
  period_from date,
  period_to   date,
  opening     numeric(12,2) default 0,
  debits      numeric(12,2) default 0,
  credits     numeric(12,2) default 0,
  interest    numeric(12,2) default 0,
  closing     numeric(12,2) default 0,
  due_date    date,
  created_by  uuid default auth.uid(),
  created_at  timestamptz not null default now()
);

-- ---------- Ledger: credit slips, payments, interest, adjustments ----------
create table if not exists public.transactions (
  id            uuid primary key default gen_random_uuid(),
  kind          text not null check (kind in ('slip','payment','interest','debit_note','credit_note')),
  customer_id   uuid not null references public.customers(id),
  vehicle_id    uuid references public.vehicles(id),
  vehicle_no    text,
  date          date not null default current_date,
  product       text,                 -- petrol | diesel | lube
  product_id    uuid references public.products(id),
  product_name  text,
  qty           numeric(12,3),
  rate          numeric(10,2),
  gst_rate      numeric(5,2) default 0,
  amount        numeric(12,2) not null check (amount > 0),
  slip_no       text,
  driver        text,
  odometer      numeric,
  po_no         text,
  mode          text,                 -- cash | upi | cheque | bank
  ref_no        text,
  note          text,
  flags         text,
  status        text not null default 'pending' check (status in ('pending','approved','rejected')),
  reject_reason text,
  bill_id       uuid references public.bills(id),
  created_by    uuid,
  created_at    timestamptz not null default now(),
  approved_by   uuid,
  approved_at   timestamptz
);
create index if not exists tx_customer_idx on public.transactions(customer_id, date);
create index if not exists tx_status_idx   on public.transactions(status);
create index if not exists veh_customer_idx on public.vehicles(customer_id);
create index if not exists bills_customer_idx on public.bills(customer_id, period_to);

-- ---------- Helper functions ----------
create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and active);
$$;

create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and active and role = 'owner');
$$;

-- First person to sign up becomes the (active) owner; everyone after is inactive staff
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  select count(*) into n from public.profiles;
  insert into public.profiles (id, email, name, phone, role, active)
  values (new.id, new.email,
          coalesce(new.raw_user_meta_data->>'name', ''),
          new.raw_user_meta_data->>'phone',
          case when n = 0 then 'owner' else 'staff' end,
          n = 0);
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Staff entries are always 'pending'; owner entries are auto-approved.
create or replace function public.tx_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.created_by := auth.uid();
  new.created_at := now();
  new.bill_id    := null;
  if public.is_owner() then
    new.status := 'approved'; new.approved_by := auth.uid(); new.approved_at := now();
  else
    if new.kind not in ('slip','payment') then
      raise exception 'Only the owner can add interest or adjustments';
    end if;
    new.status := 'pending'; new.approved_by := null; new.approved_at := null; new.reject_reason := null;
  end if;
  return new;
end $$;
drop trigger if exists tx_before_insert on public.transactions;
create trigger tx_before_insert before insert on public.transactions
  for each row execute function public.tx_before_insert();

create or replace function public.tx_before_update() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status is distinct from old.status and new.status in ('approved','rejected') then
    new.approved_by := auth.uid(); new.approved_at := now();
  end if;
  new.created_by := old.created_by; new.created_at := old.created_at;
  return new;
end $$;
drop trigger if exists tx_before_update on public.transactions;
create trigger tx_before_update before update on public.transactions
  for each row execute function public.tx_before_update();

-- ---------- Row Level Security ----------
alter table public.profiles     enable row level security;
alter table public.settings     enable row level security;
alter table public.rates        enable row level security;
alter table public.products     enable row level security;
alter table public.customers    enable row level security;
alter table public.vehicles     enable row level security;
alter table public.bills        enable row level security;
alter table public.transactions enable row level security;

-- profiles: members see the team; you always see yourself; only owner changes roles/activation
drop policy if exists p_read on public.profiles;
create policy p_read on public.profiles for select using (public.is_member() or id = auth.uid());
drop policy if exists p_owner_update on public.profiles;
create policy p_owner_update on public.profiles for update using (public.is_owner()) with check (public.is_owner());

-- master data: everyone active can read, only owner writes
do $$
declare tb text;
begin
  foreach tb in array array['settings','rates','products','customers','vehicles','bills'] loop
    execute format('drop policy if exists m_read on public.%I', tb);
    execute format('create policy m_read on public.%I for select using (public.is_member())', tb);
    execute format('drop policy if exists m_owner_ins on public.%I', tb);
    execute format('create policy m_owner_ins on public.%I for insert with check (public.is_owner())', tb);
    execute format('drop policy if exists m_owner_upd on public.%I', tb);
    execute format('create policy m_owner_upd on public.%I for update using (public.is_owner()) with check (public.is_owner())', tb);
  end loop;
end $$;

-- transactions: all active members read & add (staff entries go pending); only owner approves/edits; nobody deletes
drop policy if exists t_read on public.transactions;
create policy t_read on public.transactions for select using (public.is_member());
drop policy if exists t_insert on public.transactions;
create policy t_insert on public.transactions for insert with check (public.is_member());
drop policy if exists t_owner_update on public.transactions;
create policy t_owner_update on public.transactions for update using (public.is_owner()) with check (public.is_owner());

-- ---------- Live updates for the approval queue ----------
do $$ begin
  alter publication supabase_realtime add table public.transactions;
exception when others then null; end $$;
